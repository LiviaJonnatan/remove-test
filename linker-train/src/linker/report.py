"""Compare trained runs with every method the 11 Oct linking test scored, on the same passages.

Writes <out>/report.json and <out>/report.md. Every number is computed here from predictions.jsonl
files and the saved baselines; nothing is typed in.

Three comparisons:
1. All cited test passages (n=490): the trained model against BM25, the hybrid and the feature rerankers.
2. The 232 passages Sonnet and Haiku answered: the same, plus both models, with cost per 1,000 passages.
3. A cascade: the trained model answers every passage and Sonnet answers the ones it is least sure of.
   The share sent to Sonnet is chosen on half the comments and scored on the other half, both ways.
"""

from __future__ import annotations

import json
import random
from pathlib import Path

import numpy as np

from linker import data as D
from linker.compare import SAVED, saved_ranks
from linker.metrics import accuracy, paired

SHARES = [round(x, 2) for x in np.arange(0.0, 1.01, 0.05)]


def read_preds(run: Path, split: str = "test") -> dict[tuple[str, str], dict]:
    out = {}
    for line in (run / "predictions.jsonl").read_text().splitlines():
        p = json.loads(line)
        if p["split"] == split:
            out[(p["qid"], p["label"])] = p
    return out


def pct(a: list[float]) -> str:
    return f"{100 * a[0]:.1f}% ({100 * a[1]:.1f} to {100 * a[2]:.1f})"


def diff(d: list[float]) -> str:
    return f"{d[0]:+.1f} ({d[1]:+.1f} to {d[2]:+.1f})"


def cascade(model_ranks, margins, llm_ranks, llm_cost, comments, seed: int = 0) -> dict:
    """Send the share s of passages with the smallest margin to the LLM. Returns the curve on all
    passages, and a share picked on one half of the comments then scored on the other."""
    n = len(model_ranks)
    m_hit = np.asarray(model_ranks) == 1
    l_hit = np.asarray(llm_ranks) == 1
    cost = np.asarray(llm_cost, dtype=float)

    def at(share, idx):
        idx = np.asarray(idx)
        k = int(round(share * len(idx)))
        sub = idx[np.argsort(np.asarray(margins)[idx], kind="stable")]
        send = np.zeros(len(idx), bool)
        send[:k] = True
        hit = np.where(send, l_hit[sub], m_hit[sub])
        return float(hit.mean()), float(cost[sub][send].sum() / len(idx) * 1000)

    curve = [
        {"share": s, "acc@1": round(at(s, range(n))[0], 4), "usd_per_1000": round(at(s, range(n))[1], 2)}
        for s in SHARES
    ]
    # Pick the smallest share reaching 95% of the LLM's accuracy on one half; score it on the other.
    target = 0.95 * l_hit.mean()
    names = sorted(set(comments))
    random.Random(seed).shuffle(names)
    half = set(names[: len(names) // 2])
    folds = [
        [i for i, c in enumerate(comments) if c in half],
        [i for i, c in enumerate(comments) if c not in half],
    ]
    held = []
    for pick, score in ((folds[0], folds[1]), (folds[1], folds[0])):
        chosen = next((s for s in SHARES if at(s, pick)[0] >= 0.95 * l_hit[pick].mean()), 1.0)
        acc, usd = at(chosen, score)
        held.append(
            {"share_chosen": chosen, "acc@1": round(acc, 4), "usd_per_1000": round(usd, 2), "n": len(score)}
        )
    pooled_acc = sum(h["acc@1"] * h["n"] for h in held) / n
    pooled_usd = sum(h["usd_per_1000"] * h["n"] for h in held) / n
    return {
        "curve": curve,
        "target_acc@1": round(float(target), 4),
        "held_out": held,
        "held_out_pooled": {
            "acc@1": round(pooled_acc, 4),
            "usd_per_1000": round(pooled_usd, 2),
            "share_of_llm_acc": round(pooled_acc / l_hit.mean(), 3),
            "share_of_llm_cost": round(pooled_usd / (cost.sum() / n * 1000), 3),
        },
    }


def report(root: Path, runs: list[Path], out: Path) -> dict:
    data = D.load(root)
    test = D.scored(data.test, data.rules)
    saved = saved_ranks(root, test)
    comments = [p["comment"] for p in test]
    res: dict = {"n_test": len(test), "runs": {}}
    lines = [
        "# Linker: trained encoder against the saved methods",
        "",
        "Generated by `python src/main.py report`. Top-1 accuracy, 95% interval from resampling comments.",
        "",
    ]

    methods: dict[str, list[int]] = {m: saved[m] for m in SAVED}
    for run in runs:
        preds = read_preds(run)
        ranks = [preds[(p["qid"], p["section"])]["rank"] for p in test if (p["qid"], p["section"]) in preds]
        if len(ranks) != len(test):
            continue  # a run that did not score every test passage (one held-out docket) is reported alone
        methods[f"trained:{run.name}"] = ranks
        res["runs"][run.name] = {"margins": [preds[(p["qid"], p["section"])]["margin"] for p in test]}

    # 1. all cited test passages
    lines += ["## All cited test passages", "", "| Method | n | Top-1 | Top-5 |", "|---|---|---|---|"]
    res["all"] = {}
    for m, r in methods.items():
        a = accuracy(r, comments)
        res["all"][m] = a
        lines.append(f"| {SAVED.get(m, m)} | {a['n']} | {pct(a['acc@1'])} | {100 * a['acc@5'][0]:.1f}% |")
    trained = [m for m in methods if m.startswith("trained:")]
    if trained:
        lines += [
            "",
            "Paired differences in top-1, same passages:",
            "",
            "| Comparison | Points (95% interval) |",
            "|---|---|",
        ]
        res["all_paired"] = {}
        for t in trained:
            for m in ("hybrid", "bge", "sup_lodo_generic_gbm", "sup_in_knn_gbm"):
                d = paired(methods[t], methods[m], comments)
                res["all_paired"][f"{t} - {m}"] = d
                lines.append(f"| {t} minus {SAVED[m]} | {diff(d)} |")

    # 2. the Sonnet subset
    idx = [i for i, p in enumerate(test) if saved["sonnet"][i] is not None and saved["haiku"][i] is not None]
    sub_c = [comments[i] for i in idx]
    lines += [
        "",
        f"## The {len(idx)} passages Sonnet and Haiku answered",
        "",
        "| Method | Top-1 | Top-5 | $ per 1,000 passages |",
        "|---|---|---|---|",
    ]
    res["llm_subset"] = {"n": len(idx)}
    every = {**methods, "haiku": saved["haiku"], "sonnet": saved["sonnet"]}
    for m, r in every.items():
        rr = [r[i] for i in idx]
        a = accuracy(rr, sub_c)
        usd = 1000 * float(np.mean([saved[f"{m}_cost"][i] for i in idx])) if m in ("haiku", "sonnet") else 0.0
        res["llm_subset"][m] = {**a, "usd_per_1000": round(usd, 2)}
        lines.append(f"| {SAVED.get(m, m)} | {pct(a['acc@1'])} | {100 * a['acc@5'][0]:.1f}% | {usd:.2f} |")
    if trained:
        lines += ["", "| Comparison | Points (95% interval) |", "|---|---|"]
        for t in trained:
            for m in ("sonnet", "haiku", "sup_in_knn_gbm"):
                d = paired([methods[t][i] for i in idx], [every[m][i] for i in idx], sub_c)
                res["llm_subset"][f"{t} - {m}"] = d
                lines.append(f"| {t} minus {SAVED.get(m, m)} | {diff(d)} |")

    # 3. cascade
    for t in trained:
        name = t.split(":", 1)[1]
        margins = res["runs"][name]["margins"]
        c = cascade(
            [methods[t][i] for i in idx],
            [margins[i] for i in idx],
            [saved["sonnet"][i] for i in idx],
            [saved["sonnet_cost"][i] for i in idx],
            sub_c,
        )
        res.setdefault("cascade", {})[name] = c
        h = c["held_out_pooled"]
        lines += [
            "",
            f"## Cascade: {name} first, Sonnet on the least sure",
            "",
            f"Share sent to Sonnet picked on half the comments (smallest share reaching 95% of Sonnet's "
            f"top-1 there), scored on the other half, both ways: **{100 * h['acc@1']:.1f}% top-1 at "
            f"${h['usd_per_1000']:.2f} per 1,000 passages**, {100 * h['share_of_llm_acc']:.0f}% of Sonnet's "
            f"accuracy at {100 * h['share_of_llm_cost']:.0f}% of its cost.",
            "",
            "| Share to Sonnet | Top-1 | $ per 1,000 |",
            "|---|---|---|",
        ]
        lines += [
            f"| {r['share']:.0%} | {100 * r['acc@1']:.1f}% | {r['usd_per_1000']:.2f} |"
            for r in c["curve"][::2]
        ]

    for r in res["runs"].values():
        r.pop("margins", None)
    out.mkdir(parents=True, exist_ok=True)
    (out / "report.json").write_text(json.dumps(res, indent=1))
    (out / "report.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))
    return res
